const mediaGrid = document.querySelector("#media-grid");
const watchlistGrid = document.querySelector("#watchlist-grid");
const searchInput = document.querySelector("#search");
const emptyMessage = document.querySelector("#empty-message");
const watchlistEmpty = document.querySelector("#watchlist-empty");
const watchlistCount = document.querySelector("#watchlist-count");
const filterButtons = document.querySelectorAll("[data-filter]");
const detailRoot = document.querySelector("#detail-root")
let currentFilter = "all";
let watchlist = [];

try {
    const saved = JSON.parse(localStorage.getItem("rewind-watchlist") || "[]");
    if (Array.isArray(saved)) watchlist = saved.filter(id => media.some(item => item.id === id));
} catch { watchlist = []; }

function sourceFor(item) {
    return item.type === "movie" ? "Letterboxd" : "Serializd";
}

function makePoster(item) {
    const poster = document.createElement("div");
    poster.className = "poster-art";
    poster.style.setProperty("--poster-color", item.colour || "#6c6252");
    if (item.poster) {
        const img = document.createElement("img");
        img.className = "poster-image";
        img.src = item.poster;
        img.alt = `${item.title} alternative poster`;
        img.loading = "lazy";
        img.addEventListener("error", () => { 
            img.remove(); 
            poster.classList.remove("has-image");
        });
        poster.classList.add("has-image");
        poster.appendChild(img);
    }
    const frame = document.createElement("div");
    frame.className = "poster-frame";
    frame.setAttribute("aria-hidden", "true")
    poster.appendChild(frame);
    return poster;
}

function createCard(item) {
    const card = document.createElement("article");
    card.className = "media-card";
    const link = document.createElement("a");
    link.className = "poster-link";
    link.href = `title.html?id=${encodeURIComponent(item.id)}`;
    link.setAttribute("aria-label", `Open details for ${item.title}`);
    link.appendChild(makePoster(item));

    const info = document.createElement("div");
    info.className = "card-info";
    const kicker = document.createElement("div");
    kicker.className = "card-kicker";
    const kind = document.createElement("span");
    kind.textContent = item.type === "movie" ? "Film" : "TV show";
    const year = document.createElement("span");
    year.textContent = String(item.year);
    kicker.append(kind, year);
    const title = document.createElement("h3");
    title.textContent = item.title;
    const genre = document.createElement("p");
    genre.className = "card-meta";
    genre.textContent = item.genre;
    const rating = document.createElement("p");
    rating.className = "card-rating";
    rating.textContent = item.rating !== "Not added yet"
        ? `${sourceFor(item)}  ·  ${item.rating}`
        : `${sourceFor(item)}  ·  rating to add`
    
    const actions = document.createElement("div");
    actions.className = "card-actions";
    const details = document.createElement("a");
    details.className = "small-button";
    details.href = link.href;
    details.textContent = "Little details ↗";
    const save = document.createElement("button");
    save.className = "small-button";
    save.type = "button";
    function updateSave() {
        const isSaved = watchlist.includes(item.id);
        save.textContent = isSaved ? "♥ Saved" : "♡ Save For Later";
        save.classList.toggle("is-saved", isSaved);
        save.setAttribute("aria-pressed", String(isSaved));
    }
    save.addEventListener("click", () => {
        watchlist = watchlist.includes(item.id)
            ? watchlist.filter(id => id !== item.id)    
            : [...watchlist, item.id]
        localStorage.setItem("rewind-watchlist", JSON.stringify(watchlist));
        renderCollection();
    });
    updateSave();
    actions.append(details, save);
    info.append(kicker, title, genre, rating, actions);
    card.append(link, info);
    return card;
}

function renderCollection() {
    if (!mediaGrid) return;
    const query = searchInput ? searchInput.value.trim().toLowerCase() : "";
    const filtered = media.filter(item => {
        const typeMatches = currentFilter === "all" || item.type === currentFilter;
        const text = `${item.title} ${item.genre} ${item.year} ${item.description}`.toLowerCase();
        return typeMatches && text.includes(query);
    });
    mediaGrid.replaceChildren(...filtered.map(createCard));
    if (emptyMessage) emptyMessage.hidden = filtered.length > 0;
    const count = document.querySelector("#collection-count");
    if (count) count.textContent = `${filtered.length} different types of media displayed in this search ✷`;
    if (watchlistGrid) {
        const saved = media.filter(item => watchlist.includes(item.id));
        watchlistGrid.replaceChildren(...saved.map(createCard));
        if (watchlistEmpty) watchlistEmpty.hidden = saved.length > 0;
        if (watchlistCount) watchlistCount.textContent = String(saved.length);
    }
}

function makeDetailPage() {
    if (!detailRoot) return;
    const id = Number(new URLSearchParams(window.location.search).get("id"));
    const item = media.find(entry => entry.id === id);
    if (!item) {
        detailRoot.replaceChildren();
        detailRoot.className = "not-found";
        const eyebrow = document.createElement("p"); eyebrow.className = "eyebrow"; eyebrow.textContent = "PAGE NOT FOUND";
        const heading = document.createElement("h1"); heading.textContent = "The page wandered off.";
        const message = document.createElement("p"); message.textContent = "We couldn't find that title in your scrapbook.";
        const back = document.createElement("a"); back.className = "ink-button"; back.href = "index.html#collection"; back.textContent = "Back to the scrapbook ↗";
        detailRoot.append(eyebrow, heading, message, back);
        return;
    }
    document.title = `${item.title} | REWIND`;
    detailRoot.replaceChildren();
    const back = document.createElement("a"); back.className = "back-link"; back.href = "index.html#collection"; back.textContent = "← BACK TO THE SCRAPBOOK";
    const layout = document.createElement("div"); layout.className = "detail-layout";
    const posterColumn = document.createElement("div"); posterColumn.className = "detail-poster"; posterColumn.appendChild(makePoster(item));
    const copy = document.createElement("div"); copy.className = "detail-copy";
    const eyebrow = document.createElement("p"); eyebrow.className = "eyebrow"; eyebrow.textContent = item.type === "movie" ? "A FILM FROM THE ARCHIVE" : "A SERIES FROM THE ARCHIVE";
    const heading = document.createElement("h1"); heading.textContent = item.title;
    const facts = document.createElement("div"); facts.className = "detail-facts";
    [String(item.year), item.genre, item.type === "movie" ? "Movie": "TV series"].forEach(value => {
        const pill = document.createElement("span"); pill.className = "fact-pill"; pill.textContent = value; facts.appendChild(pill);
    });
    const rule1 = document.createElement("hr"); rule1.className = "detail-rule";
    const synopsisHeading = document.createElement("h2"); synopsisHeading.textContent = "A Short Overview:";
    const synopsis = document.createElement("p"); synopsis.className = "detail-description"; synopsis.textContent = item.description;
    const rule2 = document.createElement("hr"); rule2.className = "detail-rule";
    const ratingHeading = document.createElement("h2"); ratingHeading.textContent = "Rating & Type of Media:";
    const panel = document.createElement("div"); panel.className = "rating-panel";
    const ratingBox = document.createElement("div"); ratingBox.className = "rating-box";
    const ratingLabel = document.createElement("span"); ratingLabel.textContent = `${sourceFor(item)} rating`;
    const ratingValue = document.createElement("strong"); ratingValue.textContent = item.rating;
    ratingBox.append(ratingLabel, ratingValue);
    const typeBox = document.createElement("div"); typeBox.className = "rating-box";
    const typeLabel = document.createElement("span"); typeLabel.textContent = "Filed under";
    const typeValue = document.createElement("strong"); typeValue.textContent = item.type === "movie" ? "Movies" : "TV shows";
    typeBox.append(typeLabel, typeValue); panel.append(ratingBox, typeBox);
    const actions = document.createElement("div"); actions.className = "detail-actions";
    const save = document.createElement("button"); save.type = "button"; save.className = "ink-button";
    function updateDetailSave() { save.textContent = watchlist.includes(item.id) ? "♥ Saved" : "♡ Save For Later"; }
    save.addEventListener("click", () => {
        watchlist = watchlist.includes(item.id) ? watchlist.filter(savedId => savedId !== item.id) : [...watchlist, item.id];
        localStorage.setItem("rewind-watchlist", JSON.stringify(watchlist));
        updateDetailSave();
    });
    updateDetailSave();
    const all = document.createElement("a"); all.className = "outline-button"; all.href = "index.html"; all.textContent = "Back to Homepage";
    actions.append(save, all);
    copy.append(eyebrow, heading, facts, rule1, synopsisHeading, synopsis, rule2, ratingHeading, panel, actions);
    layout.append(posterColumn, copy);
    detailRoot.append(back, layout);
}

if (searchInput) searchInput.addEventListener("input", renderCollection);
filterButtons.forEach(button => button.addEventListener("click", () => {
    currentFilter = button.dataset.filter;
    filterButtons.forEach(other => other.classList.toggle("is-active", other === button));
    renderCollection();
}));
document.querySelectorAll("[data-jump-filter]").forEach(link => link.addEventListener("click", () => {
    currentFilter = link.dataset.jumpFilter;
    filterButtons.forEach(button => button.classList.toggle("is-active", button.dataset.filter === currentFilter));
    if (searchInput) searchInput.value = "";
    renderCollection();
}));
renderCollection();
makeDetailPage();
